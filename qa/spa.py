from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={'width':1280,'height':800})
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e))); pg.on('console',lambda m: m.type=='error' and errs.append(m.text))
    navs=[]; pg.on('framenavigated',lambda f: navs.append(f.url))
    pg.goto('http://127.0.0.1:8787/'); pg.evaluate('window.__mark=1')
    def st(): return pg.evaluate('[location.pathname+location.hash, document.title, !!window.__mark, document.querySelector("nav.main [aria-current]")?.textContent, document.querySelector("h1").textContent, Math.round(scrollY)]')
    pg.click('nav.pills a[href="/fleet/"]'); pg.wait_for_timeout(400); print('pill fleet',st())
    pg.click('nav.main a[href="/method/"]'); pg.wait_for_timeout(400); print('menu method',st())
    pg.mouse.wheel(0,1500); pg.wait_for_timeout(300); y=pg.evaluate('scrollY')
    pg.click('nav.main a[href="/harnesses/"]'); pg.wait_for_timeout(400); print('harnesses',st())
    pg.go_back(); pg.wait_for_timeout(500); print('back (expect y',round(y),')',st())
    pg.go_back(); pg.wait_for_timeout(500); print('back',st())
    pg.goto('http://127.0.0.1:8787/'); pg.evaluate('window.__mark=1')
    pg.click('a[href="/failures/#faults"]'); pg.wait_for_timeout(500); print('hash link',st())
    pg.click('.theme button[data-t=dark]'); pg.wait_for_timeout(400); print('theme after nav', pg.evaluate('document.documentElement.dataset.theme'))
    pg.goto('http://127.0.0.1:8787/data/'); pg.evaluate('window.__mark=1')
    h=pg.evaluate('[...document.querySelectorAll("main a")].find(a=>/\\.json$/.test(a.pathname)).getAttribute("href")'); print('json link',h)
    pg.click(f'main a[href="{h}"]'); pg.wait_for_timeout(500); print('after json', pg.url, pg.evaluate('!!window.__mark'))
    print('errors',errs)
    b.close()
